// دسته‌ی هنری یک رویداد را برمی‌گرداند.
export function artCat(ev) {
  const hay = ((ev.title || '') + ' ' + (ev.text || '') + ' ' + (ev.t2 || ''));
  for (const [cat, keys] of RULES) {
    for (const k of keys) if (hay.includes(k)) return cat;
  }
  return 'court'; // پیش‌فرض امن: صحنه‌ی دربار
}

export function artSrc(cat) { return `assets/ev/${cat}.jpg`; }

// دسته‌هایی که فایل نقاشی‌شان ساخته شده. هر دسته‌ی تازه اینجا اضافه شود
// وگرنه رویداد به آیکون برمی‌گردد (تصویر شکسته نشان داده نمی‌شود).
export const ART_READY = new Set([
  'court', 'battle', 'revolt', 'factory', 'siege', 'navy', 'funeral', 'birth', 'coronation',
]);

// تصویر رویداد: اگر خودش img داشت همان، وگرنه از روی دسته — و
// تنها در صورتی که نقاشی آن دسته واقعاً موجود باشد.
export function eventImg(ev) {
  if (ev.img) return ev.img;
  const c = artCat(ev);
  return ART_READY.has(c) ? artSrc(c) : null;
}
